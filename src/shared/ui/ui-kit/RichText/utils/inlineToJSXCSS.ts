export function inlineToJSXCSS(inlineStyles: string) {
  const styles: CSSProperties = {};

  const revertCSSProps = Object.entries(CSSProps).reduce(
    (acc, [jsxStyle, htmlStyle]) => {
      acc[htmlStyle] = jsxStyle as any;
      return acc;
    },
    {} as Partial<Record<string, keyof CSSProperties>>
  );

  for (const style of inlineStyles.split(";")) {
    const [prop, value] = style.split(":");

    if (Object.prototype.hasOwnProperty.call(revertCSSProps, prop)) {
      (styles as any)[revertCSSProps[prop] as any] = value;
    }
  }

  return styles;
}
