export const UserDropdown: React.FC = () => {
   const { data, logout } = useAuth();
   const [isActive, setActive] = React.useState(false);
   const ref = useClickOutside(() => setActive(false));

   if (!data) {
      return null;
   }

   const handleLogout = () => {
      logout();
   };

   return (
      <div className={css.ud} ref={ref}>
         <button className={css.ud_btn} onClick={() => setActive(!isActive)}>
            <ProfileIcon />
         </button>
         {isActive && (
            <div className={css.ud_dropdown}>
               <a className={css.ud_dropdown_link}>→ Membership</a>
               <Button variant="black" className={css.ud_logout_btn} onClick={handleLogout}>
                  Logout
               </Button>
            </div>
         )}
      </div>
   );
};
